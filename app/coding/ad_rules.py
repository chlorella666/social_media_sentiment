"""广告/官方内容规则预标（2.6，2026-08-16）。

用途：给「广告/官方内容」打 ad_flag，供用户选择"计入 / 剔除"（默认计入；
剔除时仅情感统计排除，采集漏斗/关键词效果保留并注明）。人工复核兜底：
规则命中只是建议，审核视图可确认/取消/补标。

设计原则（用户确认，2026-08-16）：
- 默认计入：广告也存在于消费者视线，正面广告本身是市场信号；
- 识别 = 规则预标 + 人工复核；不用 LLM 新字段（省费用、schema 不动）；
- 剔除范围 = 仅情感统计（分布/均分/维度/情感词榜），漏斗与关键词效果保留。
"""

from __future__ import annotations

from app.coding.cleaner import is_official_page

# 保守信号词：只收"营销/官方活动"语义明确的词，避免误伤用户真实讨论。
# 命中任一即建议标记广告/官方（人工复核可取消）。
AD_MARKERS = [
    "广告", "推广", "商单", "软广", "软文", "宣发", "官方活动", "官方发布",
    "发布会", "新品发布", "新品上市", "新品首发", "预约", "预售", "预购", "众筹",
    "开售", "首发", "首发价", "限时", "限量发售", "福利", "抽奖", "转发抽奖",
    "免单", "代言", "体验官", "品牌大使", "爆款", "促销", "优惠", "折扣",
    "满减", "领券", "优惠券", "团购", "秒杀", "补贴", "以旧换新", "会员日",
    "品牌日", "周年庆", "双十一", "618", "开屏", "物料", "海报", "种草清单",
    "直播带货", "直播间",
]


def ad_reason(text: str, title: str = "") -> str:
    """返回命中的广告/官方特征（官方标题或首个信号词）；未命中返回空串。"""
    if title and is_official_page(title):
        return "官方页面标题"
    hay = f"{title} {text}"
    for kw in AD_MARKERS:
        if kw in hay:
            return kw
    return ""


def is_ad(text: str, title: str = "") -> bool:
    """规则预标：命中官方标题或任一营销信号词 → True。"""
    return bool(ad_reason(text, title))
